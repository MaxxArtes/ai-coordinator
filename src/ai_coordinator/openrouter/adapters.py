"""Specialized modular adapters for OpenRouter modalities (Phase 4C.1).

Defines isolated contracts and metric capture for:
1. Text / Chat Completion (TextModelAdapter)
2. Embeddings Vectorization (EmbeddingModelAdapter)
3. Document Context Reranking (RerankModelAdapter, e.g. Nemotron)
4. Structured Decision Formulation (DecisionModelAdapter)
5. Audio / Voice Processing (SpeechModelAdapter)

All adapters enforce:
- FreeCostGuard authorization and fail-closed validation.
- Modality compatibility verification (IncompatibleModalityError).
- Preventative secret scrubbing and embedded credential detection (ConfidentialDataDetectedError).
- Explicit metric provenance classification (MEASURED, ESTIMATED, SYNTHETIC, UNKNOWN).
- Offline mock engine and optional opt-in OpenRouterHttpTransport.
"""
